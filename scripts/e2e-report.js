'use strict';

/**
 * Turn Playwright's JSON output (coverage/e2e-results.json) into
 * docs/FRONTEND_TEST_REPORT.md, so the report always reflects an actual run.
 *   npm run test:e2e:report
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'coverage', 'e2e-results.json'), 'utf8'));
const staticCheck = fs.existsSync(path.join(ROOT, 'coverage', 'frontend-check.txt'))
  ? fs.readFileSync(path.join(ROOT, 'coverage', 'frontend-check.txt'), 'utf8').trim()
  : 'not run';

const rows = [];
function walk(suite, trail) {
  const here = suite.title && !suite.title.endsWith('.js') ? [...trail, suite.title] : trail;
  for (const spec of suite.specs || []) {
    for (const t of spec.tests) {
      const result = t.results[t.results.length - 1] || {};
      rows.push({ file: spec.file, group: here.join(' › '), title: spec.title, status: result.status || t.status, ms: result.duration || 0 });
    }
  }
  for (const child of suite.suites || []) walk(child, here);
}
for (const s of data.suites) walk(s, []);

const count = (st) => rows.filter((r) => r.status === st).length;
const passed = count('passed');
const failed = rows.length - passed - count('skipped');

let md = `# Vault24 — Frontend Test Report

_Generated by \`npm run test:e2e:report\` from Playwright's JSON output. Do not edit by hand._

| | |
|---|---|
| Run started (UTC) | ${data.stats.startTime} |
| Browser | Chromium (Playwright ${data.config.version}) against a real, freshly seeded server |
| End-to-end tests | **${passed} passed**, ${failed} failed, ${count('skipped')} skipped, ${rows.length} total |
| Duration | ${(data.stats.duration / 1000).toFixed(1)} s |
| Static frontend check | ${staticCheck} |
| Overall | ${failed === 0 ? '**PASS**' : '**FAIL**'} |

What these tests cover: real logins for all three roles; every customer, staff and admin workflow against the live API; server-side failures (declined transfers, invalid PDFs, name mismatches); duplicate submission; a dropped connection after the bank committed a transfer (safe retry with the same idempotency key); horizontal overflow and clipped money values at 10 widths (320–1920 px); keyboard use, focus and reduced motion; axe-core WCAG 2.x A/AA scans; and a clean browser console. Any unexpected console error fails a test.

`;

const byFile = {};
for (const r of rows) (byFile[r.file] ||= []).push(r);
for (const [file, list] of Object.entries(byFile).sort()) {
  md += `\n## \`e2e/${file}\` — ${list.filter((r) => r.status === 'passed').length}/${list.length} passed\n`;
  let last = null;
  for (const r of list) {
    if (r.group !== last) { md += `\n**${r.group || '(top level)'}**\n\n`; last = r.group; }
    const mark = r.status === 'passed' ? '✅' : r.status === 'skipped' ? '⏭️' : '❌';
    md += `- ${mark} ${r.title.replace(/\|/g, '\\|')} _(${(r.ms / 1000).toFixed(1)} s)_\n`;
  }
}

const failures = rows.filter((r) => !['passed', 'skipped'].includes(r.status));
md += `\n## Failures\n\n${failures.length ? failures.map((f) => `- ${f.file}: ${f.group} › ${f.title} (${f.status})`).join('\n') : 'None.'}\n`;

fs.writeFileSync(path.join(ROOT, 'docs', 'FRONTEND_TEST_REPORT.md'), md);
console.log(`docs/FRONTEND_TEST_REPORT.md written: ${passed}/${rows.length} passed.`);
