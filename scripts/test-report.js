'use strict';

/**
 * Turn Jest's machine-readable output into docs/TEST_REPORT.md, so the report
 * always reflects an actual run and is never typed by hand.
 *   npm run test:report
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const results = JSON.parse(fs.readFileSync(path.join(ROOT, 'coverage', 'test-results.json'), 'utf8'));
const summaryPath = path.join(ROOT, 'coverage', 'coverage-summary.json');
const coverage = fs.existsSync(summaryPath) ? JSON.parse(fs.readFileSync(summaryPath, 'utf8')).total : null;

const pct = (k) => (coverage ? `${coverage[k].pct}% (${coverage[k].covered}/${coverage[k].total})` : 'n/a');
const when = new Date(results.startTime).toISOString();

let md = `# Vault24 — Test Report

_Generated by \`npm run test:report\` from Jest's JSON output. Do not edit by hand._

| | |
|---|---|
| Run started (UTC) | ${when} |
| Node.js | ${process.version} |
| Test suites | ${results.numPassedTestSuites} passed, ${results.numFailedTestSuites} failed, ${results.numTotalTestSuites} total |
| Tests | **${results.numPassedTests} passed**, ${results.numFailedTests} failed, ${results.numPendingTests} skipped, ${results.numTotalTests} total |
| Overall result | ${results.success ? '**PASS**' : '**FAIL**'} |

## Coverage (src/ only)

| Metric | Coverage |
|---|---|
| Statements | ${pct('statements')} |
| Branches | ${pct('branches')} |
| Functions | ${pct('functions')} |
| Lines | ${pct('lines')} |

## Results by suite
`;

const suites = [...results.testResults].sort((a, b) => a.name.localeCompare(b.name));
for (const suite of suites) {
  const file = path.relative(ROOT, suite.name);
  const passed = suite.assertionResults.filter((t) => t.status === 'passed').length;
  md += `\n### \`${file}\` — ${passed}/${suite.assertionResults.length} passed\n\n`;
  let lastGroup = null;
  for (const t of suite.assertionResults) {
    const group = t.ancestorTitles.join(' › ');
    if (group !== lastGroup) {
      md += `\n**${group || '(top level)'}**\n\n`;
      lastGroup = group;
    }
    const mark = t.status === 'passed' ? '✅' : t.status === 'failed' ? '❌' : '⏭️';
    md += `- ${mark} ${t.title.replace(/\|/g, '\\|')}\n`;
  }
}

const failures = suites.flatMap((s) => s.assertionResults.filter((t) => t.status === 'failed').map((t) => `${path.relative(ROOT, s.name)}: ${t.fullName}`));
md += `\n## Failures\n\n${failures.length ? failures.map((f) => `- ${f}`).join('\n') : 'None.'}\n`;

fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'TEST_REPORT.md'), md);
console.log(`docs/TEST_REPORT.md written: ${results.numPassedTests}/${results.numTotalTests} passed.`);
